<p>
    Für Verträge, Beschlüsse und Aktionärslisten können Signaturanfragen erstellt werden.
    Standardmäßig ist der manuelle Signaturworkflow aktiv (Unterschrift auf Papier oder externem Weg,
    Statuspflege im System).
</p>

<h2 class="h6 mt-4">Signaturanfrage erstellen</h2>
<ol>
    <li>Öffnen Sie <strong>Müller Holding AG &rarr; Unterschriften</strong> und klicken Sie auf
        <strong>Neue Signaturanfrage</strong>, oder starten Sie den Workflow direkt aus einem
        finalisierten Vertrag bzw. Beschluss.</li>
    <li>Wählen Sie das zu unterzeichnende PDF-Dokument.</li>
    <li>Fügen Sie die Unterzeichner mit Rolle (z. B. Vorstand, Aufsichtsratsvorsitzender, Darlehensgeber)
        und E-Mail-Adresse hinzu.</li>
    <li>Versenden bzw. übergeben Sie das Dokument zur Unterschrift und setzen Sie die Anfrage auf
        <strong>Gesendet</strong>.</li>
</ol>

<h2 class="h6 mt-4">Status pflegen und abschließen</h2>
<ol>
    <li>Pflegen Sie je Unterzeichner den Status: gesendet, geöffnet, unterschrieben, abgelehnt.</li>
    <li>Laden Sie nach vollständiger Unterzeichnung das <strong>signierte PDF</strong> über
        <strong>Signiertes Dokument anhängen</strong> hoch.</li>
    <li>Die Anfrage erhält den Status <strong>Abgeschlossen</strong>; das Ursprungsobjekt
        (Vertrag, Beschluss) wird entsprechend fortgeschrieben, z. B. auf "Unterschrieben".</li>
</ol>

<div class="alert alert-warning small mt-3 mb-0">
    Externe Signaturdienste (z. B. DocuSign, Adobe Sign) sind als Schnittstelle vorbereitet, aber noch
    nicht angebunden. Bis zur Anbindung ist ausschließlich der manuelle Workflow verfügbar.
</div>
