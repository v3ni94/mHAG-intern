<p>
    Willkommen im Intranet der Müller Holding AG. Diese Anleitung führt Sie durch die ersten Schritte
    nach Ihrer Anmeldung.
</p>

<h2 class="h6 mt-4">1. Anmeldung und Zwei-Faktor-Authentifizierung</h2>
<ol>
    <li>Melden Sie sich mit Ihrer E-Mail-Adresse und Ihrem Passwort an.</li>
    <li>Für Administratoren, Vorstand und Aufsichtsrat ist die Zwei-Faktor-Authentifizierung verpflichtend.
        Öffnen Sie dazu oben rechts das Benutzermenü und wählen Sie <strong>Zwei-Faktor-Authentifizierung</strong>.</li>
    <li>Scannen Sie den QR-Code mit einer Authenticator-App (z. B. auf Ihrem Diensttelefon) und bestätigen Sie
        die Einrichtung mit einem sechsstelligen Code.</li>
    <li>Bewahren Sie die angezeigten Wiederherstellungscodes sicher auf.</li>
</ol>

<h2 class="h6 mt-4">2. Orientierung</h2>
<ol>
    <li>Das <strong>Dashboard</strong> zeigt den Block "Heute relevant" (überfällige und heute fällige Zahlungen,
        ablaufende Verträge und Dokumente, offene Wiedervorlagen), die wichtigsten Kennzahlen und Diagramme.</li>
    <li>Über die Seitenleiste erreichen Sie alle Module: Finanzen, Stammdaten, Verträge &amp; Dokumente,
        Müller Holding AG und Organisation.</li>
    <li>Die <strong>globale Suche</strong> oben findet Personen, Unternehmen, Darlehensnummern und mehr.</li>
    <li>Mit dem Augen-Symbol aktivieren Sie den <strong>Datenschutzmodus</strong>: Geldbeträge werden ausgeblendet,
        etwa für Besprechungen am Bildschirm.</li>
</ol>

<h2 class="h6 mt-4">3. Empfohlene Reihenfolge beim Aufbau des Datenbestands</h2>
<ol>
    <li>Personen anlegen (Stammdaten, Adressen, Bankkonten, Ausweisdokumente).</li>
    <li>Unternehmen anlegen und Organe (Vorstand, Aufsichtsrat) erfassen.</li>
    <li>Darlehen mit Vertragsdaten und Zinskonditionen anlegen; das System erzeugt den Zahlungsplan.</li>
    <li>Dokumente zu den jeweiligen Akten hochladen.</li>
    <li>Benutzer einladen und Rollen sowie Datenbereiche zuweisen.</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Grundprinzip des Systems: SOLL (vertraglich geplant) und IST (tatsächlich erfasst) werden strikt getrennt.
    Solange keine Abweichung erfasst ist, gilt planmäßige Erfüllung als "systemseitig angenommen" und wird
    ausdrücklich so gekennzeichnet.
</div>
