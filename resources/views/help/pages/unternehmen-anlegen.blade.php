<p>
    Unternehmen werden wie Personen im zentralen Geschäftspartnerstamm geführt und besitzen eine
    eigene Unternehmensakte mit Organen, Beziehungen und Dokumenten.
</p>

<h2 class="h6 mt-4">Unternehmen anlegen</h2>
<ol>
    <li>Öffnen Sie in der Seitenleiste <strong>Stammdaten &rarr; Unternehmen</strong>.</li>
    <li>Klicken Sie auf <strong>Neues Unternehmen</strong>.</li>
    <li>Erfassen Sie Firmenname, Rechtsform, Registergericht und Registernummer (z. B. HRB),
        Gründungsdatum sowie USt-ID.</li>
    <li>Speichern Sie. Die Unternehmensakte wird geöffnet.</li>
</ol>

<h2 class="h6 mt-4">Unternehmensakte vervollständigen</h2>
<ol>
    <li>Erfassen Sie Geschäftsadresse, Kontaktdaten und Bankkonten in den jeweiligen Tabs.</li>
    <li>Hinterlegen Sie im Tab <strong>Organe</strong> Geschäftsführer, Vorstände, Prokuristen und
        Aufsichtsräte mit Beginn der Bestellung, Vertretungsregelung und gegebenenfalls Befreiung
        von den Beschränkungen der Selbstkontrahierung. Beendete Organstellungen werden nie gelöscht,
        sondern mit Enddatum abgeschlossen (Historie).</li>
    <li>Erfassen Sie im Tab <strong>Beziehungen</strong> Konzernverhältnisse (Mutter, Tochter, Schwester,
        Beteiligung) inklusive Beteiligungsquote.</li>
    <li>Laden Sie im Tab <strong>Dokumente</strong> Handelsregisterauszug, Satzung und weitere Unterlagen hoch.</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Ansprechpartner eines Unternehmens sind reguläre Personen aus dem Personenstamm und werden über die
    Funktion "Ansprechpartner" verknüpft, nicht doppelt erfasst.
</div>
