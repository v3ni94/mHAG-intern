<p>
    Aktienübertragungen (Verkauf, Schenkung, Übertragung) durchlaufen einen Workflow vom Entwurf bis
    zur Wirksamkeit. Erst die wirksame Bewegung verändert den Bestand.
</p>

<h2 class="h6 mt-4">Aktienbewegung erfassen</h2>
<ol>
    <li>Öffnen Sie <strong>Müller Holding AG &rarr; Aktienbewegungen</strong> und klicken Sie auf
        <strong>Neue Bewegung</strong>.</li>
    <li>Wählen Sie die Art (Kauf, Verkauf, Übertragung, Schenkung, Kapitalmaßnahme).</li>
    <li>Wählen Sie Verkäufer und Käufer aus dem Aktionärsstamm.</li>
    <li>Erfassen Sie Stückzahl, gegebenenfalls Preis je Aktie, das Vertragsdatum und den
        <strong>wirtschaftlichen Übergang</strong> (Stichtag, ab dem die Aktien dem Erwerber zugerechnet werden).</li>
    <li>Speichern Sie den Entwurf. Das System vergibt die Bewegungsnummer.</li>
</ol>

<h2 class="h6 mt-4">Workflow bis zur Wirksamkeit</h2>
<ol>
    <li>Optional: Vertrag erzeugen und unterschreiben lassen; zugehörigen Beschluss verknüpfen.</li>
    <li>Klicken Sie auf <strong>Wirksam setzen</strong>, sobald alle Voraussetzungen erfüllt sind.</li>
    <li>Das System prüft dabei, dass der Verkäufer zum Übergangsstichtag über genügend Aktien verfügt,
        und schreibt den Bestand fort.</li>
</ol>

<h2 class="h6 mt-4">Storno</h2>
<ul>
    <li>Fehlerhafte wirksame Bewegungen werden nicht gelöscht, sondern über <strong>Stornieren</strong>
        durch eine Gegenbuchung neutralisiert. Beide Buchungen bleiben in der Historie sichtbar.</li>
</ul>

<div class="alert alert-info small mt-3 mb-0">
    Historische Übertragungen erfassen Sie mit dem tatsächlichen wirtschaftlichen Übergangsdatum in der
    Vergangenheit; stichtagsbezogene Auswertungen und Aktionärslisten berücksichtigen sie automatisch.
</div>
