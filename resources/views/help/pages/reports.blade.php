<p>
    Das Reportmodul stellt Auswertungen über Darlehen, offene Posten, Zinsen, Sicherheiten,
    Aktionäre, Beschlüsse und Organe bereit. Jeder Report ist filterbar und exportierbar.
</p>

<h2 class="h6 mt-4">Report aufrufen</h2>
<ol>
    <li>Öffnen Sie <strong>Organisation &rarr; Reports</strong>.</li>
    <li>Wählen Sie den gewünschten Report, z. B. <strong>Darlehensbestandsliste</strong>,
        <strong>Offene Posten</strong>, <strong>Zinsen Soll/Ist</strong> oder <strong>Aktionärsliste</strong>.</li>
    <li>Setzen Sie die Filter (Zeitraum, Jahr, Status, Stichtag) und klicken Sie auf <strong>Filtern</strong>.</li>
</ol>

<h2 class="h6 mt-4">Exportieren</h2>
<ol>
    <li>Klicken Sie oben rechts auf <strong>PDF</strong>, <strong>XLSX</strong> oder <strong>CSV</strong>.</li>
    <li>Die gesetzten Filter werden in den Export übernommen.</li>
    <li>CSV-Dateien sind Semikolon-getrennt und UTF-8-codiert; sie lassen sich direkt in Excel öffnen.</li>
</ol>

<h2 class="h6 mt-4">Hinweise zur Interpretation</h2>
<ul>
    <li>Der Report <strong>Zinsen Soll/Ist</strong> weist bestätigte Zahlungen und systemseitig
        angenommene Zahlungen getrennt aus. Eine Annahme ist keine bestätigte Zahlung.</li>
    <li>Der Report <strong>Überfällige Darlehen</strong> berücksichtigt nur tatsächlich erfasste
        Ausfälle und Teilzahlungen.</li>
    <li>Die <strong>Aktionärsliste</strong> ist stichtagsfähig: Wählen Sie ein Datum, um die
        historische Struktur zu diesem Tag auszuwerten.</li>
    <li>Externe Benutzer sehen in allen Reports ausschließlich die Daten ihrer zugeordneten Entitäten.</li>
</ul>
