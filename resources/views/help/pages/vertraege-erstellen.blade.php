<p>
    Verträge werden aus versionierten Vorlagen mit Platzhaltern erzeugt. Beim Finalisieren entsteht
    ein unveränderlicher Snapshot samt PDF im Corporate Design.
</p>

<h2 class="h6 mt-4">Vertrag aus Vorlage erstellen</h2>
<ol>
    <li>Öffnen Sie <strong>Verträge &amp; Dokumente &rarr; Verträge</strong> und klicken Sie auf
        <strong>Neuer Vertrag</strong>. Alternativ starten Sie direkt aus der Darlehensakte.</li>
    <li>Wählen Sie eine Vertragsvorlage (z. B. Darlehensvertrag) in der gewünschten Version.</li>
    <li>Wählen Sie das zugehörige Darlehen. Die Standardplatzhalter (Parteien, Betrag, Zinssatz,
        Laufzeit) werden automatisch aus den Fachdaten befüllt.</li>
    <li>Prüfen Sie die Vorschau; fehlende Platzhalter werden aufgelistet und müssen ergänzt werden.</li>
    <li>Speichern Sie den Vertrag zunächst als <strong>Entwurf</strong>.</li>
</ol>

<h2 class="h6 mt-4">Finalisieren und unterschreiben</h2>
<ol>
    <li>Klicken Sie auf <strong>Finalisieren</strong>. Der Vertragstext wird als Snapshot eingefroren
        und das PDF erzeugt; nachträgliche Änderungen am Text sind ausgeschlossen.</li>
    <li>Starten Sie bei Bedarf einen Signaturworkflow (siehe Anleitung "Digitale Signaturen") oder
        laden Sie den manuell unterschriebenen Vertrag als Dokument hoch.</li>
    <li>Nachträgliche Änderungen (Laufzeitverlängerung, Zinsänderung, Stundung) erfassen Sie als
        <strong>Vertragsnachtrag</strong> mit Wirkungsdatum; der Ursprungsvertrag bleibt unverändert.</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Vertragsvorlagen verwalten Sie unter Verträge &amp; Dokumente; jede inhaltliche Änderung erzeugt
    eine neue Vorlagenversion, damit bestehende Verträge ihrer Ursprungsversion zugeordnet bleiben.
</div>
