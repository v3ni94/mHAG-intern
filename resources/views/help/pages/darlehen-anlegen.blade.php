<p>
    Ein Darlehen verbindet Darlehensgeber und Darlehensnehmer aus dem Geschäftspartnerstamm mit
    Vertragsdaten, Zinskonditionen und dem automatisch erzeugten Zahlungsplan (SOLL).
</p>

<h2 class="h6 mt-4">Darlehen anlegen</h2>
<ol>
    <li>Öffnen Sie <strong>Finanzen &rarr; Darlehen</strong> und klicken Sie auf <strong>Neues Darlehen</strong>.</li>
    <li>Wählen Sie <strong>Darlehensgeber</strong> und <strong>Darlehensnehmer</strong> (Person oder Unternehmen).</li>
    <li>Erfassen Sie Vertragsdatum, <strong>Wirkungsbeginn</strong> (ab wann das Darlehen fachlich gilt),
        Darlehensbetrag, Laufzeit bzw. Endfälligkeit und Kündigungsfrist.</li>
    <li>Legen Sie die Zinskondition fest: Zinssatz in Prozent p. a., Zinsmethode (z. B. act/365, 30/360),
        Zinsfälligkeit (monatlich, quartalsweise, jährlich oder endfällig) und das Tilgungsmodell
        (endfällig, Rate, Annuität, offen). Zinslose Darlehen erfassen Sie mit Zinssatz 0.</li>
    <li>Optional: Gebühren (einmalig oder laufend), Verzugszinsregelung, Risikoeinstufung, Sachbearbeiter.</li>
    <li>Speichern Sie. Das System vergibt automatisch die Darlehensnummer (Muster DAR-JAHR-NNNNN)
        und erzeugt den Zahlungsplan ab dem Wirkungsbeginn.</li>
</ol>

<h2 class="h6 mt-4">Auszahlung erfassen</h2>
<ol>
    <li>Öffnen Sie das Darlehen und wechseln Sie zum Tab <strong>Auszahlungen</strong>.</li>
    <li>Planen Sie die Auszahlung mit Betrag und Datum.</li>
    <li>Bestätigen Sie die Auszahlung, sobald sie tatsächlich geflossen ist. Erst dadurch wird der
        Kapitalverlauf wirksam und die Zinsberechnung beginnt auf dem ausgezahlten Kapital.</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Der Darlehensstatus (Entwurf, zur Unterschrift, aktiv, überfällig usw.) wird über Statusübergänge
    gepflegt; jede Änderung bleibt in der Chronik nachvollziehbar.
</div>
