<p>
    Geplante Auszahlungen können bestätigt, als nicht erfolgt markiert oder storniert werden.
    Der Kapitalverlauf und damit die Zinsberechnung folgen immer dem tatsächlichen Zustand.
</p>

<h2 class="h6 mt-4">Nicht erfolgte Auszahlung erfassen</h2>
<ol>
    <li>Öffnen Sie das Darlehen und wechseln Sie zum Tab <strong>Auszahlungen</strong>.</li>
    <li>Wählen Sie die betroffene Auszahlung.</li>
    <li>Markieren Sie sie als <strong>nicht erfolgt</strong>. Der Istbetrag wird 0,00 EUR.</li>
    <li>Das System korrigiert alle Folgewerte: Es entstehen keine Zinsen auf nicht ausgezahltes Kapital;
        Zahlungsplan und Forderungsstand werden ab dem geplanten Auszahlungsdatum neu berechnet.</li>
</ol>

<h2 class="h6 mt-4">Abweichenden Auszahlungsbetrag bestätigen</h2>
<ol>
    <li>Öffnen Sie die geplante Auszahlung im Tab <strong>Auszahlungen</strong>.</li>
    <li>Wählen Sie <strong>Bestätigen</strong> und erfassen Sie den tatsächlichen Betrag und das
        tatsächliche Datum (z. B. geplant 100.000,00 EUR am 01.03., tatsächlich 80.000,00 EUR am 05.03.).</li>
    <li>Wählen Sie die Herkunft (manuell bestätigt oder Bankimport).</li>
    <li>Die Zinsberechnung basiert ab sofort auf dem tatsächlich ausgezahlten Kapital ab dem
        tatsächlichen Datum.</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Bereits bestätigte Auszahlungen werden nicht bearbeitet oder gelöscht, sondern über Storno bzw.
    Korrekturbuchung angepasst. Jede Änderung wird im Neuberechnungsprotokoll und im Audit-Trail dokumentiert.
</div>
