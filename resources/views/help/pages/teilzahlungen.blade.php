<p>
    Zahlt ein Darlehensnehmer weniger als den Sollbetrag, erfassen Sie eine Teilzahlung.
    Sollbetrag, Istbetrag und offener Rest werden getrennt geführt.
</p>

<h2 class="h6 mt-4">Teilzahlung über die Monatsübersicht erfassen</h2>
<ol>
    <li>Öffnen Sie das Darlehen und wechseln Sie zum Tab <strong>Soll/Ist</strong>.</li>
    <li>Wählen Sie den betroffenen Monat.</li>
    <li>Tragen Sie den tatsächlich gezahlten Betrag als <strong>Istbetrag</strong> ein
        (z. B. Soll 500,00 EUR, Ist 200,00 EUR).</li>
    <li>Der Status wechselt auf <strong>"Teilweise bezahlt"</strong>; der offene Rest (300,00 EUR)
        wird automatisch ausgewiesen.</li>
    <li>Speichern Sie und warten Sie die Neuberechnung ab.</li>
</ol>

<h2 class="h6 mt-4">Teilzahlung über einen Zahlungseingang erfassen</h2>
<ol>
    <li>Erfassen Sie den Zahlungseingang unter <strong>Finanzen &rarr; Zahlungen</strong> mit dem
        tatsächlichen Betrag.</li>
    <li>Das System verteilt den Betrag nach der Verrechnungsreihenfolge (Kosten, Gebühren,
        Verzugszinsen, Zinsen, Tilgung) und setzt die betroffene Planposition auf
        <strong>"Teilweise bezahlt"</strong>.</li>
    <li>Der offene Rest bleibt als Forderung bestehen und erscheint in den offenen Posten.</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Der offene Rest einer Teilzahlung bleibt sichtbar, bis er durch eine weitere Zahlung ausgeglichen,
    erlassen oder anderweitig ausgebucht wird. Jeder Schritt bleibt in der Historie nachvollziehbar.
</div>
