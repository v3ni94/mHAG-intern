<p>
    Privatpersonen werden im zentralen Geschäftspartnerstamm geführt. Eine Person kann gleichzeitig
    Darlehensgeber, Darlehensnehmer, Aktionär und Organmitglied sein.
</p>

<h2 class="h6 mt-4">Person anlegen</h2>
<ol>
    <li>Öffnen Sie in der Seitenleiste <strong>Stammdaten &rarr; Personen</strong>.</li>
    <li>Klicken Sie auf <strong>Neue Person</strong>.</li>
    <li>Erfassen Sie die Stammdaten: Anrede, Titel, Vorname, Nachname, Geburtsdatum, Geburtsort,
        Staatsangehörigkeit. Pflichtfelder sind markiert.</li>
    <li>Speichern Sie. Die Personenakte wird geöffnet.</li>
</ol>

<h2 class="h6 mt-4">Personenakte vervollständigen</h2>
<ol>
    <li>Ergänzen Sie im Tab <strong>Adressen</strong> die Hauptadresse (Straße, Hausnummer, PLZ, Ort).
        Weitere Adressen (z. B. Korrespondenzadresse) können mit Gültigkeitszeitraum erfasst werden.</li>
    <li>Hinterlegen Sie im Tab <strong>Kontakt</strong> E-Mail-Adressen und Telefonnummern und markieren Sie
        den bevorzugten Kanal.</li>
    <li>Erfassen Sie im Tab <strong>Bankkonten</strong> IBAN, BIC und Kontoinhaber.</li>
    <li>Im Tab <strong>Ausweisdokumente</strong> erfassen Sie Personalausweis oder Reisepass mit Ablaufdatum.
        Das System erinnert automatisch vor Ablauf (Dashboard, Kalender, Benachrichtigungen).</li>
    <li>Im Tab <strong>Dokumente</strong> sehen Sie alle mit der Person verknüpften Dateien.</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Die Rollen einer Person (Darlehensgeber, Aktionär usw.) ergeben sich automatisch aus den Fachdaten,
    zum Beispiel aus einem Darlehen oder einer Aktienposition. Sie müssen keine Rolle manuell setzen.
</div>
