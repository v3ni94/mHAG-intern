<p>
    Der Aktionärsstamm der Müller Holding AG wird im Gesellschaftsmodul geführt. Der Aktienbestand
    je Aktionär wird immer aus den wirksamen Aktienbewegungen berechnet, nie manuell gepflegt.
</p>

<h2 class="h6 mt-4">Aktionär aufnehmen</h2>
<ol>
    <li>Legen Sie die Person bzw. das Unternehmen zunächst im Stammdatenmodul an, falls noch nicht vorhanden.</li>
    <li>Öffnen Sie <strong>Müller Holding AG &rarr; Aktionäre</strong> und klicken Sie auf
        <strong>Neuer Aktionär</strong>.</li>
    <li>Wählen Sie die Entität und erfassen Sie das Eintrittsdatum. Das System vergibt die Aktionärsnummer.</li>
    <li>Der tatsächliche Bestand entsteht erst durch eine wirksame Aktienbewegung
        (z. B. Kauf oder Übertragung, siehe Anleitung "Aktien übertragen").</li>
</ol>

<h2 class="h6 mt-4">Bestand und Historie einsehen</h2>
<ul>
    <li>Die Aktionärsliste zeigt je Aktionär Stückzahl und Quote zum gewählten Stichtag.</li>
    <li>Über das Stichtagsdatum lässt sich jede historische Aktionärsstruktur exakt rekonstruieren
        ("Wer hielt am 01.01.2026 wie viele Aktien?").</li>
    <li>Mit <strong>Aktionärsliste erstellen</strong> erzeugen Sie ein unveränderliches PDF-Dokument
        mit Snapshot und Prüfsumme, geeignet als Nachweis (z. B. gegenüber Registergericht oder Notar).</li>
</ul>

<div class="alert alert-info small mt-3 mb-0">
    Grundkapital und Gesamtaktienzahl sind zentral hinterlegt. Die Summe aller Bestände kann die
    Gesamtaktienzahl nie überschreiten; das System prüft dies bei jeder Bewegung.
</div>
