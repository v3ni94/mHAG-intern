<p>
    Beschlüsse von Vorstand, Aufsichtsrat und Hauptversammlung werden mit Antrag, Begründung,
    Abstimmung und Ergebnis strukturiert erfasst und als PDF dokumentiert.
</p>

<h2 class="h6 mt-4">Beschluss anlegen</h2>
<ol>
    <li>Öffnen Sie <strong>Müller Holding AG &rarr; Beschlüsse</strong> und klicken Sie auf
        <strong>Neuer Beschluss</strong>.</li>
    <li>Wählen Sie die Art: Vorstandsbeschluss, Aufsichtsratsbeschluss, Hauptversammlung oder
        Umlaufbeschluss. Das System vergibt die passende Beschlussnummer (VOR-, AR-, HV-, UB-).</li>
    <li>Erfassen Sie Titel, Antragsteller, Antragstext, Begründung und den Beschlusstext.</li>
    <li>Fügen Sie die Teilnehmer hinzu und vermerken Sie etwaige Interessenkonflikte.</li>
    <li>Verknüpfen Sie den Beschluss bei Bedarf mit Darlehen, Verträgen oder Aktienbewegungen.</li>
</ol>

<h2 class="h6 mt-4">Abstimmung und Abschluss</h2>
<ol>
    <li>Starten Sie die Abstimmung und erfassen Sie je Teilnehmer Ja, Nein, Enthaltung oder abwesend.</li>
    <li>Tragen Sie das tatsächliche Beschlussdatum ein (bei historischen Beschlüssen das Originaldatum;
        das Erfassungsdatum bleibt getrennt gespeichert).</li>
    <li>Halten Sie das Ergebnis fest (angenommen, abgelehnt, vertagt, zurückgezogen).
        Das System zählt nur die Stimmen; eine rechtliche Bewertung nimmt es nicht vor.</li>
    <li>Erzeugen Sie das <strong>Beschluss-PDF</strong> und starten Sie bei Bedarf den Signaturworkflow
        (Status "Zur Unterschrift").</li>
</ol>

<div class="alert alert-info small mt-3 mb-0">
    Das Beschlussregister (auch als Report verfügbar) listet alle Beschlüsse mit Nummer, Datum, Art,
    Ergebnis und Status und lässt sich nach Jahr, Art und Status filtern und exportieren.
</div>
